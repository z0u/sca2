"""The in-context grammar: token layout, the clean-context invariant, label positions, determinism."""

from __future__ import annotations

import numpy as np
import pytest

from sca.data import incontext as ic
from sca.data.named_colors import WordTokenizer
from sca.data.ops import DARKEN, LIGHTEN, MIX, NAMES, OPS
from sca.config import TokenizerConfig

RED, GREEN, GREY, WHITE, BLACK = (15, 0, 0), (0, 15, 0), (6, 6, 6), (15, 15, 15), (0, 0, 0)


# --- Token layout -----------------------------------------------------------------------------


def test_context_length_formula():
    for k in range(0, 5):
        assert ic.context_length(k) == 6 * k + 6
        assert ic.context_length(k, verify=True) == 6 * k + 8


def test_completion_context_words():
    ex = ic.Example(RED, GREEN, GREY, "true", "mix")
    ctx = ic.Context("mix", (ex,), WHITE, BLACK, GREY)
    assert ctx.words == [
        NAMES[RED], "?", NAMES[GREEN], "=", NAMES[GREY], ",",
        NAMES[WHITE], "?", NAMES[BLACK], "=", NAMES[GREY], "\n",
    ]  # fmt: skip
    assert len(ctx.words) == ctx.n_tokens == ic.context_length(1)
    assert ctx.words.count(ic.EXAMPLE_SEP) == 1  # closes the one example, not the query
    assert ctx.words[-1] == "\n"


def test_verification_context_words():
    ex = ic.Example(RED, GREEN, GREY, "true", "mix")
    verify = ic.Verification(GREY, True, "true", "mix")
    ctx = ic.Context("mix", (ex,), WHITE, BLACK, GREY, verify)
    assert ctx.words == [
        NAMES[RED], "?", NAMES[GREEN], "=", NAMES[GREY], ",",
        NAMES[WHITE], "?", NAMES[BLACK], "=", NAMES[GREY], ic.VERIFY_MARK, ic.TRUE_TOKEN, "\n",
    ]  # fmt: skip
    assert ctx.n_tokens == ic.context_length(1, verify=True)


def test_two_examples_no_separator_before_query():
    ex = ic.Example(RED, GREEN, GREY, "true", "mix")
    ctx = ic.Context("mix", (ex, ex), WHITE, BLACK, GREY)
    words = ctx.words
    # every example ends in a comma; only the query (the last unit) ends in a newline
    assert words.count(",") == 2
    assert words.count("\n") == 1
    assert words[-1] == "\n"


# --- The clean-context invariant (rho=cube_rate=0) --------------------------------------------


def _consistent_ops(op_table, examples):
    """Ops whose deterministic (exact) output agrees with every shown example — the discrete analogue of the
    posterior at rho=0. Not necessarily a singleton: two ops can coincide on a handful of examples, especially
    at small k ("where the op table allows", per the task's own phrasing)."""
    return {o.name for o in op_table if all(o(ex.lhs, ex.rhs) == ex.answer for ex in examples)}


@pytest.mark.parametrize("k", [1, 3, 4])
@pytest.mark.parametrize("seed", [0, 1, 2])
def test_clean_context_is_consistent_with_only_the_hidden_op(k, seed):
    """At rho=0 every example (and the query) is generated by the hidden op alone, under nearest rounding, so the
    hidden op is always exactly consistent with what's shown, and — as k grows — usually the only op that is
    (empirically ~63% at k=1, ~94% at k=3, ~98% at k=4 over table `OPS`; calibrated by direct simulation)."""
    rng = np.random.default_rng(seed)
    unique = 0
    n = 30
    for _ in range(n):
        hidden = OPS[int(rng.integers(len(OPS)))]
        ctx = ic.sample_context(OPS, hidden, k, rho=0.0, rng=rng)
        assert all(ex.source == "true" for ex in ctx.examples)
        assert all(ex.answer == hidden(ex.lhs, ex.rhs) for ex in ctx.examples)
        assert ctx.query_answer == hidden(ctx.query_lhs, ctx.query_rhs)

        consistent = _consistent_ops(OPS, ctx.examples)
        assert hidden.name in consistent  # the hidden op is never ruled out by its own examples
        unique += len(consistent) == 1

    # loose lower bounds well under the calibrated rates, just enough to catch a broken generator
    threshold = {1: 0.4, 3: 0.8, 4: 0.9}[k]
    assert unique / n >= threshold


def test_replacement_noise_only_at_rho_one():
    rng = np.random.default_rng(0)
    ctx = ic.sample_context(OPS, MIX, k=4, rho=1.0, rng=rng, cube_rate=0.0)
    assert all(ex.source == "noise" for ex in ctx.examples)
    assert all(ex.drawn_op != "mix" for ex in ctx.examples)  # "another op": never the hidden one
    assert ctx.query_answer == MIX(ctx.query_lhs, ctx.query_rhs)  # the query is always clean


def test_cube_noise_only_at_cube_rate_one():
    rng = np.random.default_rng(0)
    ctx = ic.sample_context(OPS, MIX, k=4, rho=0.0, rng=rng, cube_rate=1.0)
    assert all(ex.source == "cube" and ex.drawn_op is None for ex in ctx.examples)


def test_verification_verdict_matches_the_true_answer_whatever_branch_produced_it():
    """The verdict is a fact about the candidate, not a record of which branch drew it: a noise or cube draw
    that happens to equal the true answer is TRUE."""
    rng = np.random.default_rng(0)
    for _ in range(200):
        ctx = ic.sample_context(OPS, MIX, k=2, rho=0.5, rng=rng, cube_rate=0.2, verify_rate=1.0)
        assert ctx.verify is not None
        assert ctx.verify.verdict == (ctx.verify.candidate == ctx.query_answer)


def test_verify_rate_gates_whether_a_context_is_a_verification_line():
    rng = np.random.default_rng(0)
    never = [ic.sample_context(OPS, MIX, k=2, rho=0.2, rng=rng, verify_rate=0.0) for _ in range(20)]
    assert all(c.verify is None for c in never)
    always = [ic.sample_context(OPS, MIX, k=2, rho=0.2, rng=rng, verify_rate=1.0) for _ in range(20)]
    assert all(c.verify is not None for c in always)


